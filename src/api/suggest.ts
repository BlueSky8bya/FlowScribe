function resolveGenres(settings: string[], moods: string[]): GenreProfile[] {
  const s = settings.map(normalize);
  const m = moods.map(normalize);
  const scored = GENRES.map((genre) => {
    const tokens = [normalize(genre.key), ...genre.aliases.map(normalize), ...genre.styleGuide.map(normalize), ...genre.flavor.ruleBias.map(normalize)];
    let score = genre.priority / 10;
    for (const token of s) if (tokens.includes(token)) score += 10;
    for (const token of m) if (tokens.includes(token)) score += 8;
    return { genre, score };
  }).sort((a, b) => b.score - a.score);

  const selected = scored.filter((v) => v.score > 6).slice(0, 3).map((v) => v.genre);
  return selected.length ? selected : [GENRES.find((g) => g.key === "현대") ?? GENRES[0]];
}

function mergeGenres(genres: GenreProfile[]) {
  return {
    primary: genres[0],
    allKeys: genres.map((g) => g.key),
    nameStyle: uniq(genres.map((g) => g.nameStyle)).join(" / "),
    styleGuide: uniq(genres.flatMap((g) => g.styleGuide)),
    directF: uniq(genres.flatMap((g) => g.namePools.directF)),
    directM: uniq(genres.flatMap((g) => g.namePools.directM)),
    directN: uniq(genres.flatMap((g) => g.namePools.directN)),
    synthF: uniq(genres.flatMap((g) => g.namePools.synthF)),
    synthM: uniq(genres.flatMap((g) => g.namePools.synthM)),
    synthN: uniq(genres.flatMap((g) => g.namePools.synthN)),
    surnames: uniq(genres.flatMap((g) => g.namePools.surnames ?? [])),
    biological: uniq(genres.flatMap((g) => g.typePools.biological)),
    agender: uniq(genres.flatMap((g) => g.typePools.agender)),
    hybrid: uniq(genres.flatMap((g) => g.typePools.hybrid)),
    jobs: uniq(genres.flatMap((g) => g.typePools.jobs)),
    legendary: uniq(genres.flatMap((g) => g.typePools.legendary)),
    atmosphere: uniq(genres.flatMap((g) => g.flavor.atmosphere)),
    relationship: uniq(genres.flatMap((g) => g.flavor.relationship)),
    conflict: uniq(genres.flatMap((g) => g.flavor.conflict)),
    behavior: uniq(genres.flatMap((g) => g.flavor.behavior)),
    object: uniq(genres.flatMap((g) => g.flavor.object)),
    sensory: uniq(genres.flatMap((g) => g.flavor.sensory)),
    taboo: uniq(genres.flatMap((g) => g.flavor.taboo)),
    ruleBias: uniq(genres.flatMap((g) => g.flavor.ruleBias)),
  };
}


function buildNameCandidates(merged: ReturnType<typeof mergeGenres>, excludeNames: string[], seed: number) {
  const rand = makeRng(seed ^ 0x9e3779b9);
  const ex = new Set(excludeNames.map(normalize));

  const cleanPool = (arr: string[]) => arr.map(cleanName).filter((n) => n && !ex.has(normalize(n)));
  return {
    female:  sample(cleanPool(merged.directF), 18, rand),
    male:    sample(cleanPool(merged.directM), 18, rand),
    neutral: sample(cleanPool(merged.directN), 10, rand),
  };
}

function buildTypeCandidates(merged: ReturnType<typeof mergeGenres>, excludeTypes: string[], seed: number): string[] {
  const rand = makeRng(seed ^ 0x85ebca6b);
  const ex = new Set(excludeTypes.map(normalize));
  const base = uniq([
    ...sample(merged.hybrid, 10, rand),
    ...sample(merged.agender, 6, rand),
    ...sample(merged.biological, 8, rand),
    ...sample(merged.jobs, 6, rand),
    ...sample(merged.legendary, 4, rand),
  ]).filter((t) => !ex.has(normalize(t)));
  return base.slice(0, 20);
}

