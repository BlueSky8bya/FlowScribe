function safeJsonParse(raw: string): unknown {
  try {
    const trimmed = raw.trim();
    const match = trimmed.match(/\[[\s\S]*\]/);
    return JSON.parse(match ? match[0] : trimmed);
  } catch {
    logWarn("api:suggest", "JSON 파싱 실패 — 빈 배열 반환", {
      raw_length: raw.length,
      raw_preview: raw.slice(0, 120),
    });
    return null;
  }
}

function postprocessCharacters(parsed: unknown, excludeNames: string[], excludeTypes: string[], seed: number): CharacterCandidate[] {
  const rand = makeRng(seed ^ 0x31415926);
  const arr = Array.isArray(parsed) ? parsed : [];
  const exNames = new Set(excludeNames.map(normalize));
  const exTypes = new Set(excludeTypes.map(normalize));
  const seen = new Set<string>();
  const out: CharacterCandidate[] = [];

  for (const item of arr) {
    if (!item || typeof item !== "object") continue;
    const obj = item as Record<string, unknown>;
    const name = cleanName(String(obj.name ?? ""));
    const personality = normalizePersonality(String(obj.personality ?? "").replace(/\s+/g, " "));
    // 모델이 "2. 복수의 화신" 처럼 번호를 붙이는 경우 제거
    const type = String(obj.type ?? "").replace(/^\d+[.\s]+/, "").replace(/[A-Za-z]/g, "").replace(/[一-龥]/g, "").trim();
    let gender = String(obj.gender ?? "") as GenderValue;

    if (!name || name.length < 2 || exNames.has(normalize(name))) continue;
    if (!type || exTypes.has(normalize(type))) continue;
    if (!personality || personality.replace(/\s/g, "").length < 25) continue;
    // 영문자 비율이 20% 이상이면 모델 오류 산출물로 간주
    const engRatio = (personality.match(/[A-Za-z]/g) ?? []).length / personality.length;
    if (engRatio > 0.2) continue;
    if (!["남성","여성","해당없음"].includes(gender)) gender = inferGender(type, rand);
    if (!isAgenderType(type) && gender === "해당없음") gender = rand() < 0.5 ? "남성" : "여성";
    if (seen.has(normalize(name))) continue;
    seen.add(normalize(name));
    out.push({ name, personality, type, gender });
    if (out.length >= 10) break;
  }

  return out;
}

