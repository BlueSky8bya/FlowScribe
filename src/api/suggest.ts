function normalize(text: string): string {
  return `${text ?? ""}`.trim().toLowerCase().replace(/\s+/g, "").replace(/[^\p{L}\p{N}]+/gu, "");
}

function uniq<T>(arr: T[]): T[] {
  return [...new Set(arr)];
}

function clamp(n: number, min: number, max: number): number {
  return Math.max(min, Math.min(max, n));
}

const KO_JOSA = /(?:이다|입니다|이에요|예요|이며|이고|이라|이란|이야|이가|이은|이는|은|는|이|가|을|를|의|와|과|로|으로|에서|에게|한테|께|도|만|까지|부터|처럼|같이|보다|마다|라고|이라고|하고|이나|나|며|고|지만|서|야|아)$/u;

function cleanName(raw: string): string {
  let name = `${raw ?? ""}`.replace(/[^\p{L}\p{N}]/gu, "").replace(/[A-Za-z]/g, "").replace(/[一-龥]/g, "").trim();
  // 모델이 "백사슴이다" 같이 서술형 어미를 붙이는 경우 제거
  name = name.replace(KO_JOSA, "");
  return name;
}

function hashString(input: string): number {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < input.length; i += 1) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function makeRng(seed: number) {
  let t = seed >>> 0;
  return () => {
    t += 0x6D2B79F5;
    let r = Math.imul(t ^ (t >>> 15), 1 | t);
    r ^= r + Math.imul(r ^ (r >>> 7), 61 | r);
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}

function shuffle<T>(arr: T[], rand: () => number): T[] {
  const out = [...arr];
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}

function sample<T>(arr: T[], count: number, rand: () => number): T[] {
  return shuffle(arr, rand).slice(0, Math.min(count, arr.length));
}

function pick<T>(arr: T[], rand: () => number): T {
  return arr[Math.floor(rand() * arr.length)];
}

function isAgenderType(typeName: string): boolean {
  return AGENDALESS_HINTS.some((hint) => typeName.includes(hint));
}

function inferGender(typeName: string, rand: () => number): GenderValue {
  if (isAgenderType(typeName)) return "해당없음";
  return rand() < 0.5 ? "남성" : "여성";
}

// 의미상 어색한 동사-목적어 패턴 필터 (모델이 소품 키워드를 억지로 끼워넣는 경우)
const AWKWARD_PATTERNS = [
  /무전기를\s*(?:항상\s*)?멍때린/,
  /(?:모서리|벽면|벽|기둥|가장자리)를?\s*(?:손가락으로\s*)?치루/,
  /치룰\s*때/,
  /를\s*멍때린/,   // "[사물]를 멍때린다" 형태 전반
];

function normalizePersonality(text: string): string {
  let cleaned = `${text ?? ""}`
    .replace(/["'`]/g, "")
    .replace(/\s+/g, " ")
    .trim();

  for (const pat of AWKWARD_PATTERNS) {
    if (pat.test(cleaned)) {
      // 해당 문장만 제거하고 나머지 문장 유지
      cleaned = cleaned
        .split(/(?<=[.。])\s*/)
        .filter(s => !AWKWARD_PATTERNS.some(p => p.test(s)))
        .join(" ")
        .trim();
      break;
    }
  }

  return cleaned.length > 200 ? cleaned.slice(0, 200).trim() : cleaned;
}

