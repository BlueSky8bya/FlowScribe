  moods: WorldSuggestSettingItem[];
  rulesToAdd: Array<{ text: string; hard: boolean }>;
  characters: Array<{
    name: string;
    gender: string;
    type: string;
    personality: string;
    initial_items: Array<{ name: string; description: string; category: string; badge_label: string }>;
  }>;
