function postprocessRules(parsed: unknown, existingRules: string[], primaryGenre?: string, biasWords?: string[]): RuleCandidate[] {
  const arr = Array.isArray(parsed) ? parsed : [];
  const ex = new Set(existingRules.map(normalize));
  const seen = new Set<string>();
  const banned = primaryGenre ? (CROSS_GENRE_BANNED[primaryGenre] ?? []) : [];
  const out: RuleCandidate[] = [];

  for (const item of arr) {
    if (!item || typeof item !== "object") continue;
    const obj = item as Record<string, unknown>;
    const val = String(obj.val ?? "").replace(/\s+/g, " ").trim().replace(/["'`]/g, "").replace(/[.。。!！?？]+$/, "");
    if (!val) continue;
    if (ex.has(normalize(val)) || seen.has(normalize(val))) continue;
    if (banned.some(kw => val.includes(kw))) continue; // 교차오염 제거
    if (/[A-Za-z]/.test(val)) continue; // 영문자 포함 규칙 제거 (모델 오류 산출물)
    // 진부한 트레이드오프 패턴 제거 (평가 스크립트 CLICHE_PATTERNS와 동기화)
    const clicheRE = /능력.{0,6}체력|마법.{0,6}소모|스킬.{0,6}소진|사용.{0,6}수명|힘을 쓰면|대가.{0,6}치러|포인트|레벨업|강해진다|약해진다|쇠약해/;
    if (clicheRE.test(val)) continue;
    // 장르 핵심 키워드가 없는 규칙은 세계관 정합성이 낮으므로 제외
    if (biasWords && biasWords.length > 0 && !biasWords.some(kw => val.includes(kw))) continue;
    // 조건절 없는 서술문은 세계관 규칙이 아니므로 제외
    const hasCond = /면|때|경우|시|한다면/.test(val);
    if (!hasCond) continue;
    seen.add(normalize(val));
    out.push({ val, hard: Boolean(obj.hard) });
    if (out.length >= 6) break;
  }

  if (out.length && !out.some((r) => r.hard)) out[out.length - 1].hard = true;
  return out;
}

function localCharacterFallback(
  _context: string,
  settings: string[],
  moods: string[],
  excludeNames: string[],
  excludeTypes: string[],
  seed: number,
): CharacterCandidate[] {
  const genres = resolveGenres(settings, moods);
  const primary = genres[0];
  const merged = mergeGenres(genres);
  const rand = makeRng(seed ^ 0xabcdef01);
  // 주 장르 이름만 사용해 교차오염 방지
  const primaryMerged = mergeGenres([primary]);
  const names = buildNameCandidates(primaryMerged, excludeNames, seed);
  const types = buildTypeCandidates(merged, excludeTypes, seed);
  const type = pick(types.length ? types : ["인간"], rand);
  const gender = inferGender(type, rand);
  const filterShort = (pool: string[]) => pool.filter(n => n.length >= 2);
  const namePool = gender === "여성" ? filterShort(names.female) : gender === "남성" ? filterShort(names.male) : filterShort(names.neutral);
  const fallbackPool = filterShort([...names.female, ...names.male, ...names.neutral]);
  const name = pick(namePool.length ? namePool : (fallbackPool.length ? fallbackPool : ["이름없음"]), rand);

  // 주 장르 행동만 사용해 교차오염 방지
  const primaryBehaviors = primary.flavor.behavior.length >= 2
    ? primary.flavor.behavior
    : merged.behavior;
  const b1 = pick(primaryBehaviors, rand);
  const b2 = pick(primaryBehaviors.filter(b => b !== b1), rand);
  const pref = pick(COMMON_PREFERENCES, rand);

  // 단순 나열이 아닌 자연스러운 흐름으로 조합
  const personality = normalizePersonality(`${b1}. ${b2}. ${pref}.`);
  return [{ name, personality, type, gender }];
}

